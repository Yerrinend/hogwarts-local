'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const context={window:{}};vm.createContext(context);
vm.runInContext(fs.readFileSync(path.join(__dirname,'../web/view.js'),'utf8'),context);
const view=context.window.RPGView;
assert.equal(view.chapterTitle('Глава 1. Письмо на коврике',1),'Письмо на коврике');
assert.equal(view.chapterTitle('Chapter 2: A letter',2),'A letter');
assert.equal(view.chapterTitle('Розділ 3 — Лист',3),'Лист');
assert.equal(view.chapterTitle('Глава 12. Чужой номер',1),'Глава 12. Чужой номер');
const story='<p>Письмо ещё не открыто.</p>';
const stats='<h2>Отношения</h2>'+Array.from({length:4},(_,i)=>`<table><tr><td>Таблица ${i+1}</td></tr></table>`).join('')+'<p>Инвентарь: письмо.</p>';
const result=view.chapterBody(story+stats,s=>s);
assert.equal((result.match(/<table>/g)||[]).length,4);
assert.ok(result.includes(stats));
assert.ok(result.startsWith('<article class="story">'+story+'</article><details'));
assert.ok(!result.includes('<details open'));
assert.equal(view.chapterBody(story,s=>s),'<article class="story">'+story+'</article>');
const proseThenTable='<p>Сцена продолжается.</p><table><tr><td>Данные</td></tr></table><p>Ещё сцена.</p>';
assert.ok(!view.chapterBody(proseThenTable,s=>s).includes('<details'));
console.log('Reader: clean titles; all four tables preserved; narrative is never collapsed without a stats heading.');
